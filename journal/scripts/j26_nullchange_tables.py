"""j26 - tables and figure for Section IX, generated from j23 / j23b JSON.

Keeps the paper's numbers tied to the result files. Emits:
  paper/sections/tab_nullchange.tex        the epoch-by-epoch trace
  paper/sections/tab_nullchange_end.tex    the endpoint comparison
  figures/fig_divergence.png               divergence against epoch
"""
import json
import sys
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt                                    # noqa: E402

JROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(JROOT))

import jlib as J                                                   # noqa: E402

SEC = JROOT / "paper" / "sections"


def main():
    J.banner("j26  section IX tables and figure")
    j23 = json.loads((J.RESULTS / "j23_pooling_order.json").read_text())
    j23b = json.loads((J.RESULTS / "j23b_divergence_trace.json").read_text())
    SEC.mkdir(parents=True, exist_ok=True)

    # ------------------------------------------------------- trace table
    L = [
        "% GENERATED by journal/scripts/j26_nullchange_tables.py",
        r"\begin{table}[t]",
        r"\caption{The two orderings of Equation~\eqref{eq:readout}, traced "
        r"through training. They are identical until a gradient is taken. "
        r"Relative divergence is in parameter $\ell_1$ norm; "
        r"$F_1$ columns are on the validation split.}",
        r"\label{tab:nullchange-trace}",
        r"\centering\tabfont",
        r"\begin{tabular}{lrr}",
        r"\toprule",
        r"Checkpoint & Difference & Rel. \\",
        r"\midrule",
        r"Parameter names & identical & --- \\",
        f"Initialisation & ${'0' if j23b['init_identical'] else '>0'}$ & --- \\\\",
        f"Forward pass (all 3 heads) & "
        f"${j23b['forward_max_diff']:.0f}$ & --- \\\\",
        f"First minibatch loss & "
        f"${abs(j23b['first_loss_fixed'] - j23b['first_loss_legacy']):.0f}$ "
        f"& --- \\\\",
        r"\midrule",
    ]
    for r in j23b["trace"]:
        L.append(f"After epoch {r['epoch']} & "
                 f"${r['abs_delta']:.3e}$ & ${r['rel_delta']:.2e}$ \\\\")
    L += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    (SEC / "tab_nullchange.tex").write_text(
        _fix_exponents("\n".join(L)) + "\n", encoding="utf-8")

    # ---------------------------------------------------- endpoint table
    m = j23["models"]
    E = [
        "% GENERATED by journal/scripts/j26_nullchange_tables.py",
        # table*: the CI column pushes this to 264pt in a 252pt column, so as
        # a single-column float it printed over the text beside it.
        r"\begin{table*}[t]",
        r"\caption{Endpoint of the two orderings after "
        f"{j23['epochs']} epochs, with "
        f"{j23['n_conf']} third-party crossings from "
        f"{j23['n_conf_designs']} designs, all correct by construction. "
        r"Intervals are design-clustered.}",
        r"\label{tab:nullchange}",
        r"\centering\tabfont",
        r"\begin{tabular}{llrrl}",
        r"\toprule",
        r"Ordering & Source & $F_1$ (gen.) & FPR (real) & 95\% CI \\",
        r"\midrule",
    ]
    label = {"reference": ("global first", "released artifact"),
             "fixed": ("global first", "reimplementation"),
             "legacy": ("seed first", "reimplementation")}
    for k in ("reference", "fixed", "legacy"):
        o, s = label[k]
        v = m[k]
        E.append(f"{o} & {s} & {v['test_id_f1']:.4f} & "
                 f"{v['conf_fpr']:.3f} & "
                 f"$[{v['ci'][0]:.3f}, {v['ci'][1]:.3f}]$ \\\\")
    E += [
        r"\midrule",
        r"\multicolumn{5}{l}{Agreement between the two orderings: "
        f"{m['legacy']['agree_with_reference']:.1%}".replace("%", r"\%")
        + r" of crossings} \\",
        r"\bottomrule", r"\end{tabular}", r"\end{table*}",
    ]
    (SEC / "tab_nullchange_end.tex").write_text("\n".join(E) + "\n",
                                                encoding="utf-8")

    # ------------------------------------------------------------ figure
    ep = [r["epoch"] for r in j23b["trace"]]
    rel = [max(r["rel_delta"], 1e-12) for r in j23b["trace"]]
    f_a = [r["val_f1_fixed"] for r in j23b["trace"]]
    f_b = [r["val_f1_legacy"] for r in j23b["trace"]]

    fig, ax = plt.subplots(figsize=(5.2, 3.0))
    ax.semilogy(ep, rel, "o-", color="#b2182b", lw=1.8, ms=5,
                label="relative parameter divergence")
    ax.set_xlabel("epoch")
    ax.set_ylabel("relative divergence", color="#b2182b")
    ax.tick_params(axis="y", labelcolor="#b2182b")
    ax.set_ylim(1e-7, 1e-1)
    ax.grid(alpha=0.25, which="both", ls=":")

    ax2 = ax.twinx()
    ax2.plot(ep, f_a, "s--", color="#2166ac", lw=1.4, ms=4,
             label="val $F_1$, global first")
    ax2.plot(ep, f_b, "^--", color="#67a9cf", lw=1.4, ms=4,
             label="val $F_1$, seed first")
    ax2.set_ylabel("validation $F_1$", color="#2166ac")
    ax2.tick_params(axis="y", labelcolor="#2166ac")
    ax2.set_ylim(0.0, 1.05)

    h1, l1 = ax.get_legend_handles_labels()
    h2, l2 = ax2.get_legend_handles_labels()
    ax.legend(h1 + h2, l1 + l2, fontsize=7, loc="lower right", framealpha=0.95)
    ax.set_title("A null change diverges while the metric does not",
                 fontsize=9)
    fig.tight_layout()
    out = J.FIGURES / "fig_divergence.png"
    fig.savefig(out, dpi=200)
    print(f"  -> {out.relative_to(J.ROOT)}")
    print(f"  -> {(SEC / 'tab_nullchange.tex').relative_to(J.ROOT)}")
    print(f"  -> {(SEC / 'tab_nullchange_end.tex').relative_to(J.ROOT)}")


def _fix_exponents(txt):
    """Turn 1.268e-03 into LaTeX math, closing the brace."""
    import re

    def repl(mo):
        mant, sign, exp = mo.group(1), mo.group(2), mo.group(3)
        return (f"{mant}\\!\\times\\!10^{{{'-' if sign == '-' else ''}"
                f"{int(exp)}}}")

    return re.sub(r"([\d.]+)e([+-])(\d+)", repl, txt)


if __name__ == "__main__":
    main()
