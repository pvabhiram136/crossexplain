"""j31 - figure and table for the 60-draw dispersion distribution (j30).

Three panels:
  left    every draw, real-CDC FPR against benchmark F1. The benchmark axis
          is a single value.
  middle  the distribution per architecture, as a strip plot over a box.
  right   the pooled histogram, which is where the shape question is settled.
"""
import json
import sys
from pathlib import Path

import matplotlib
import numpy as np

matplotlib.use("Agg")
import matplotlib.pyplot as plt                                    # noqa: E402

JROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(JROOT))

import jlib as J                                                   # noqa: E402

SEC = JROOT / "paper" / "sections"
COL = {"gat": "#2166ac", "gcn": "#b2182b", "sage": "#1b7837"}
MK = {"global_first": "o", "seed_first": "^"}


def main():
    J.banner("j31  dispersion distribution figure")
    d = json.loads((J.RESULTS / "j30_multi_dispersion.json").read_text())
    rows, archs = d["rows"], d["archs"]
    SEC.mkdir(parents=True, exist_ok=True)

    fpr = np.array([r["conf_fpr"] for r in rows])
    f1 = np.array([r["test_id_f1"] for r in rows])
    print(f"  {len(rows)} draws, test_id F1 distinct values: "
          f"{d['test_id']['n_distinct']}")

    fig, (a1, a2, a3) = plt.subplots(
        1, 3, figsize=(9.2, 3.0),
        gridspec_kw=dict(width_ratios=[1.05, 1.15, 0.95]))
    rng = np.random.default_rng(0)

    # ---- panel 1: the two axes
    for r in rows:
        a1.scatter(r["test_id_f1"] + rng.uniform(-0.004, 0.004),
                   r["conf_fpr"], marker=MK[r["pooling"]], s=42,
                   color=COL[r["arch"]], alpha=0.7, zorder=3,
                   edgecolor="white", lw=0.6)
    a1.set_xlim(0.94, 1.03)
    a1.set_ylim(-0.06, 1.09)
    a1.set_xlabel("$F_1$ on the generated benchmark")
    a1.set_ylabel("FPR, real CDC code")
    a1.axvline(1.0, color="0.5", ls=":", lw=1)
    a1.grid(alpha=0.22, ls=":")
    a1.set_title(f"{len(rows)} null-change draws", fontsize=9)
    # Every point sits near x = 1.0, so the whole left half of the panel is
    # free. Legend goes top-left, annotation bottom-left; they collided when
    # both were placed centrally.
    a1.annotate(f"benchmark range {d['test_id']['range']:.4f}",
                xy=(0.999, 0.16), xytext=(0.943, 0.05),
                fontsize=6.5, color="0.35",
                arrowprops=dict(arrowstyle="->", color="0.5", lw=0.8))
    # Colour encodes architecture and marker encodes reduction order; without
    # a key the panel is undecodable.
    from matplotlib.lines import Line2D
    keys = [Line2D([], [], marker="o", ls="", color=COL[a], ms=5,
                   label=a.upper()) for a in archs]
    keys += [Line2D([], [], marker=MK[p], ls="", color="0.45", ms=5,
                    label=p.replace("_", " ")) for p in MK]
    a1.legend(handles=keys, fontsize=6, loc="upper left", ncol=1,
              framealpha=0.95, handletextpad=0.4, borderpad=0.35)

    # ---- panel 2: per architecture
    data = [[r["conf_fpr"] for r in rows if r["arch"] == a] for a in archs]
    a2.boxplot(data, widths=0.55, medianprops=dict(color="0.2", lw=1.5),
               boxprops=dict(lw=1.0), whiskerprops=dict(lw=1.0),
               capprops=dict(lw=1.0), showfliers=False)
    for i, (a, v) in enumerate(zip(archs, data), start=1):
        a2.scatter(np.full(len(v), i) + rng.uniform(-0.16, 0.16, len(v)), v,
                   s=30, color=COL[a], alpha=0.7, zorder=3,
                   edgecolor="white", lw=0.5)
    a2.set_xticks(range(1, len(archs) + 1))
    a2.set_xticklabels([a.upper() for a in archs], fontsize=8)
    a2.set_ylim(-0.06, 1.09)
    a2.grid(alpha=0.22, ls=":", axis="y")
    a2.set_title("per architecture", fontsize=9)

    # ---- panel 3: pooled shape
    a3.hist(fpr, bins=np.linspace(0, 1, 11), orientation="horizontal",
            color="0.62", edgecolor="white", lw=0.8)
    a3.axhspan(-0.06, 0.10, color="#1b7837", alpha=0.10)
    a3.axhspan(0.90, 1.09, color="#b2182b", alpha=0.10)
    a3.set_ylim(-0.06, 1.09)
    a3.set_xlabel("draws")
    a3.grid(alpha=0.22, ls=":", axis="x")
    a3.set_title(f"{d['pooled']['n_mid']} of {d['pooled']['n']} intermediate", fontsize=9)

    fig.tight_layout()
    out = J.FIGURES / "fig_dispersion_dist.png"
    fig.savefig(out, dpi=200)
    print(f"  -> {out.relative_to(J.ROOT)}")

    # ------------------------------------------------------------- table
    p = d["pooled"]
    L = [
        "% GENERATED by journal/scripts/j31_distribution_figure.py",
        r"\begin{table}[t]",
        r"\caption{Real-code false-positive rate over "
        f"{d['n_draws']} models that are mathematically identical to one "
        r"another, varying only reduction order and an isomorphic relabeling "
        r"of the graph nodes. On the generated benchmark they span "
        f"{d['test_id']['min']:.4f} to {d['test_id']['max']:.4f}, a range of "
        # \textbf, not \emph: IEEEtran sets table captions in small caps, and
        # small-caps italic Times does not exist, so \emph here raises
        # "Font shape OT1/ptm/m/scit undefined" and gets substituted.
        f"{d['test_id']['range']:.4f}. \\textbf{{Low}} and \\textbf{{high}} count "
        r"draws below 0.10 and above 0.90.}",
        r"\label{tab:dispdist}",
        r"\centering\tabfont",
        r"\begin{tabular}{lrrrrrrr}",
        r"\toprule",
        r"Arch. & $n$ & Min & Max & Mean & SD & Low & High \\",
        r"\midrule",
    ]
    for a in archs:
        s = d["per_arch"][a]
        L.append(f"{a.upper()} & {s['n']} & {s['min']:.3f} & {s['max']:.3f} & "
                 f"{s['mean']:.3f} & {s['sd']:.3f} & {s['n_low']} & "
                 f"{s['n_high']} \\\\")
    L += [
        r"\midrule",
        f"\\textbf{{Pooled}} & {p['n']} & \\textbf{{{p['min']:.3f}}} & "
        f"\\textbf{{{p['max']:.3f}}} & {p['mean']:.3f} & {p['sd']:.3f} & "
        f"{p['n_low']} & {p['n_high']} \\\\",
        r"\bottomrule", r"\end{tabular}", r"\end{table}",
    ]
    (SEC / "tab_dispdist.tex").write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"  -> {(SEC / 'tab_dispdist.tex').relative_to(J.ROOT)}")


if __name__ == "__main__":
    main()
