"""j33 - the Section VII table: everything we can remove without being noticed.

Section VII's claim is that the generated benchmark is saturated in a strong
sense: not merely that good methods score highly, but that removing capacity,
features, and context leaves the score unchanged. This assembles that evidence
from the ablations already run.

  encoder depth       j03, depths 1 to 7, 3 seeds each
  node features       j09, leave-one-group-out
  extraction cone     j09, backward hop budget 2 to 8

Each row reports the generated split and the twelve hand-written designs, so
the contrast is visible: the first column does not move and the second does.
"""
import json
import sys
from pathlib import Path

import numpy as np

JROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(JROOT))

import jlib as J                                                   # noqa: E402

SEC = JROOT / "paper" / "sections"


def main():
    J.banner("j33  saturation table for Section VII")
    depth = json.loads((J.RESULTS / "j03_depth_ablation.json").read_text())
    abl = json.loads((J.RESULTS / "j09_ablations.json").read_text())

    rows = []
    for d in depth["depths"]:
        per = depth["per_depth"][str(d)]["per_seed"]
        rows.append(dict(
            group="depth", tag=f"{d} layer{'s' if d > 1 else ''}",
            gen=float(np.mean([s["test_id_f1"] for s in per])),
            real=float(np.mean([s["test_real_f1"] for s in per])),
            note=f"{per[0]['n_params'] / 1000:.0f}k params"))
    for g in abl["feature_groups"]:
        rows.append(dict(group="features", tag=g["tag"],
                         gen=g["test_id_f1_mean"], real=g["test_real_f1_mean"],
                         note=""))
    for h in abl["hops"]:
        rows.append(dict(group="cone", tag=h["tag"], gen=h["test_id_f1_mean"],
                         real=h["test_real_f1_mean"],
                         note=f"{h['mean_train_nodes']:.1f} nodes"))

    gen = np.array([r["gen"] for r in rows])
    real = np.array([r["real"] for r in rows])
    print(f"  {len(rows)} configurations")
    print(f"  generated split : {gen.min():.4f} to {gen.max():.4f}  "
          f"(range {np.ptp(gen):.4f}, sd {gen.std(ddof=1):.4f})")
    print(f"  hand-written    : {real.min():.4f} to {real.max():.4f}  "
          f"(range {np.ptp(real):.4f}, sd {real.std(ddof=1):.4f})")
    print(f"  ratio of ranges : {np.ptp(real) / max(np.ptp(gen), 1e-9):.1f}x")
    print(f"  configurations at or above 0.999 on the generated split: "
          f"{int((gen >= 0.999).sum())} of {len(gen)}")

    lbl = {"depth": "Encoder depth", "features": "Node features",
           "cone": "Extraction cone"}
    L = [
        "% GENERATED by journal/scripts/j33_saturation_table.py",
        r"\begin{table}[t]",
        r"\caption{Capacity, features and context removed one at a time. The "
        r"generated split spans "
        f"{np.ptp(gen):.4f} across all {len(rows)} configurations while the "
        f"hand-written designs span {np.ptp(real):.4f}. Depth rows are means "
        r"over three seeds; feature and cone rows are means over the seeds "
        r"used in the corresponding ablation.}",
        r"\label{tab:saturation}",
        r"\centering\tabfont",
        r"\begin{tabular}{llrrl}",
        r"\toprule",
        r"Varied & Setting & Gen. $F_1$ & Real $F_1$ & \\",
        r"\midrule",
    ]
    last = None
    for r in rows:
        if r["group"] != last:
            if last is not None:
                L.append(r"\addlinespace")
            L.append(f"\\multicolumn{{5}}{{l}}{{\\emph{{{lbl[r['group']]}}}}} "
                     f"\\\\")
            last = r["group"]
        tag = r["tag"].replace("_", r"\_").replace("(", "").replace(")", "")
        L.append(f" & {tag} & {r['gen']:.4f} & {r['real']:.4f} & "
                 f"{r['note']} \\\\")
    L += [
        r"\midrule",
        f"\\multicolumn{{2}}{{l}}{{\\textbf{{range}}}} & "
        f"\\textbf{{{np.ptp(gen):.4f}}} & \\textbf{{{np.ptp(real):.4f}}} & \\\\",
        r"\bottomrule", r"\end{tabular}", r"\end{table}",
    ]
    SEC.mkdir(parents=True, exist_ok=True)
    (SEC / "tab_saturation.tex").write_text("\n".join(L) + "\n",
                                            encoding="utf-8")
    print(f"  -> {(SEC / 'tab_saturation.tex').relative_to(J.ROOT)}")

    J.save("j33_saturation_table", dict(
        n_configs=len(rows), rows=rows,
        gen_min=float(gen.min()), gen_max=float(gen.max()),
        gen_range=float(np.ptp(gen)), gen_sd=float(gen.std(ddof=1)),
        real_min=float(real.min()), real_max=float(real.max()),
        real_range=float(np.ptp(real)), real_sd=float(real.std(ddof=1)),
        n_at_ceiling=int((gen >= 0.999).sum())))


if __name__ == "__main__":
    main()
