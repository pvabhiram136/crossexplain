"""j25 - emit the corpus table for Section V straight from the triage JSON.

Written so the paper's Table 1 cannot drift from `j12_corpus_triage.json`.
Regenerate with this script; never edit the .tex numbers by hand.
"""
import json
import sys
from pathlib import Path

JROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(JROOT))

import jlib as J                                                   # noqa: E402

OUT = JROOT / "paper" / "sections" / "tab_corpus.tex"

ORIGIN = {
    "github.com/lowRISC/opentitan": "OpenTitan",
    "github.com/pulp-platform/common_cells": "pulp",
    "github.com/alexforencich/verilog-axis": "verilog-axis",
    "github.com/ZipCPU/wb2axip": "wb2axip",
}


def origin_of(repo):
    for k, v in ORIGIN.items():
        if k in repo:
            return v
    return repo.rsplit("/", 1)[-1]


def esc(s):
    return s.replace("_", r"\_")


def main():
    J.banner("j25  corpus table")
    triage = json.loads((J.RESULTS / "j12_corpus_triage.json").read_text())
    rows = [r for r in triage
            if r.get("usable") and "duplicate_of" not in r]
    rows.sort(key=lambda r: (r["n_ff"], r["name"]))

    conf = J.confirmation_set()
    per_design = {}
    for s in conf:
        per_design[s["design"]] = per_design.get(s["design"], 0) + 1

    n_ff = [r["n_ff"] for r in rows]
    n_cells = [r["n_cells"] for r in rows]
    print(f"  {len(rows)} designs, {sum(per_design.values())} crossings")
    print(f"  FFs   {min(n_ff)} to {max(n_ff)}")
    print(f"  cells {min(n_cells)} to {max(n_cells)}")

    L = [
        "% GENERATED by journal/scripts/j25_corpus_table.py -- do not edit.",
        # table*, not table. With 21 rows the Origin column is wide enough
        # that the tabular overruns a single column and prints on top of the
        # body text beside it -- and a tabular inside a float sets its own
        # natural width, so LaTeX reports no overfull hbox for this. The
        # caption count is interpolated for the same reason every other
        # number in this file is: it said "sixteen" for a 21-row table.
        r"\begin{table*}[t]",
        f"\\caption{{The {len(rows)} third-party designs accepted into the "
        r"corpus.",
        r"Every design elaborates with no blackbox cells and is structurally",
        # \textbf, not \emph: see the note in j31 -- IEEEtran table captions
        # are small caps, and small-caps italic Times is an undefined shape.
        r"distinct from every other. \textbf{Cr.} is the number of distinct",
        r"crossings recovered by name-blind grouping.}",
        r"\label{tab:corpus}",
        r"\centering\tabfont",
        r"\begin{tabular}{lrrrl}",
        r"\toprule",
        r"Design & FFs & Cells & Cr. & Origin \\",
        r"\midrule",
    ]
    for r in rows:
        L.append(f"\\texttt{{{esc(r['name'])}}} & {r['n_ff']} & "
                 f"{r['n_cells']} & {per_design.get(r['name'], 0)} & "
                 f"{origin_of(r['repo'])} \\\\")
    L += [
        r"\midrule",
        f"\\textbf{{Total}} & & & \\textbf{{{sum(per_design.values())}}} & "
        f"\\textbf{{{len(rows)} designs}} \\\\",
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{table*}",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"  -> {OUT.relative_to(J.ROOT)}")

    J.save("j25_corpus_table", dict(
        n_designs=len(rows), n_crossings=sum(per_design.values()),
        ff_min=min(n_ff), ff_max=max(n_ff),
        cells_min=min(n_cells), cells_max=max(n_cells),
        crossings_per_design=per_design))


if __name__ == "__main__":
    main()
