"""j29 - the paper's central figure and table, from j24 and j28.

Every point is a model that is mathematically identical to every other point:
same architecture, data, order, hyperparameters and seed, differing only in
reduction order, node labeling, or thread count. The horizontal axis is the
benchmark the conference paper reports. The vertical axis is real CDC code.

If the benchmark measured anything about deployment behaviour, these points
would lie on a line. They lie on a vertical segment.
"""
import json
import sys
from pathlib import Path

import matplotlib
import numpy as np

matplotlib.use("Agg")
import matplotlib.pyplot as plt                                    # noqa: E402

JROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(JROOT))

import jlib as J                                                   # noqa: E402

SEC = JROOT / "paper" / "sections"
PERM = {None: "identity", 1: "perm 1", 2: "perm 2"}


def main():
    J.banner("j29  dispersion figure and table")
    j24 = json.loads((J.RESULTS / "j24_dispersion.json").read_text())
    rows, summ = j24["rows"], j24["summary"]
    SEC.mkdir(parents=True, exist_ok=True)

    fpr = np.array([r["conf"] for r in rows])
    f1 = np.array([r["test_id"] for r in rows])
    print(f"  {len(rows)} configurations")
    print(f"  test_id F1 : {f1.min():.4f} to {f1.max():.4f} "
          f"({summ['test_id']['n_distinct']} distinct value(s))")
    print(f"  conf FPR   : {fpr.min():.3f} to {fpr.max():.3f}")

    # ------------------------------------------------------------ figure
    fig, (axl, axr) = plt.subplots(1, 2, figsize=(7.0, 3.1),
                                   gridspec_kw=dict(width_ratios=[1.15, 1]))

    style = {"global_first": ("o", "#2166ac"), "seed_first": ("^", "#b2182b")}
    for pool, (mk, col) in style.items():
        sel = [r for r in rows if r["pooling"] == pool]
        axl.scatter([r["test_id"] for r in sel], [r["conf"] for r in sel],
                    marker=mk, s=64, color=col, alpha=0.85, zorder=3,
                    edgecolor="white", linewidth=0.8,
                    label=pool.replace("_", " "))
    axl.set_xlim(0.90, 1.02)
    axl.set_ylim(-0.05, 1.08)
    axl.set_xlabel("$F_1$ on the generated benchmark")
    axl.set_ylabel("false-positive rate, real CDC code")
    axl.axvline(1.0, color="0.5", ls=":", lw=1)
    axl.grid(alpha=0.25, ls=":")
    axl.legend(fontsize=7, loc="center left", framealpha=0.95)
    axl.set_title("Every point is the same model", fontsize=9)
    axl.annotate(f"all {len(rows)} at $F_1=1.0000$",
                 xy=(1.0, 0.5), xytext=(0.925, 0.52), fontsize=7,
                 color="0.35",
                 arrowprops=dict(arrowstyle="->", color="0.5", lw=0.8))

    # right panel: the two ranges side by side
    axr.boxplot([f1, fpr], widths=0.5, vert=True,
                medianprops=dict(color="#b2182b", lw=1.6),
                boxprops=dict(lw=1.1), whiskerprops=dict(lw=1.1),
                capprops=dict(lw=1.1), flierprops=dict(ms=3))
    for i, v in enumerate((f1, fpr), start=1):
        axr.scatter(np.full(len(v), i) + np.random.default_rng(0)
                    .uniform(-0.11, 0.11, len(v)), v, s=22, alpha=0.65,
                    color="#2166ac", zorder=3, edgecolor="white", lw=0.5)
    axr.set_xticks([1, 2])
    axr.set_xticklabels(["benchmark $F_1$", "real-code FPR"], fontsize=8)
    axr.set_ylim(-0.05, 1.08)
    axr.grid(alpha=0.25, ls=":", axis="y")
    axr.set_title(f"range {summ['test_id']['range']:.4f}  vs  "
                  f"{summ['conf']['range']:.3f}", fontsize=9)

    fig.tight_layout()
    out = J.FIGURES / "fig_dispersion.png"
    fig.savefig(out, dpi=200)
    print(f"  -> {out.relative_to(J.ROOT)}")

    # ------------------------------------------------------------- table
    L = [
        "% GENERATED by journal/scripts/j29_dispersion_figure.py",
        # table*: seven columns come to 262pt in a 252pt column, so as a
        # single-column float this printed into the text beside it. LaTeX
        # reports nothing for that; j50_table_widths.py measures it.
        r"\begin{table*}[t]",
        r"\caption{Twelve configurations that are mathematically identical: "
        r"same architecture, data, batch order, hyperparameters and seed, "
        r"differing only in the order of two commutative reductions, in an "
        r"isomorphic relabeling of the graph nodes, and in thread count. "
        r"The benchmark cannot distinguish them; real CDC code separates them "
        r"completely.}",
        r"\label{tab:dispersion}",
        r"\centering\tabfont",
        r"\begin{tabular}{llrrrrr}",
        r"\toprule",
        r"Pooling & Labels & Thr. & $F_1$ gen. & $F_1$ real & Wr. rec. "
        r"& FPR real \\",
        r"\midrule",
    ]
    for r in rows:
        L.append(f"{r['pooling'].replace('_', ' ')} & "
                 f"{PERM[r['node_perm']]} & {r['threads']} & "
                 f"{r['test_id']:.4f} & {r['test_real']:.4f} & "
                 f"{r['wrapped']:.3f} & {r['conf']:.3f} \\\\")
    L += [
        r"\midrule",
        f"\\multicolumn{{3}}{{l}}{{\\textbf{{range}}}} & "
        f"\\textbf{{{summ['test_id']['range']:.4f}}} & "
        f"{summ['test_real']['range']:.4f} & "
        f"{summ['wrapped']['range']:.3f} & "
        f"\\textbf{{{summ['conf']['range']:.3f}}} \\\\",
        r"\bottomrule", r"\end{tabular}", r"\end{table*}",
    ]
    (SEC / "tab_dispersion.tex").write_text("\n".join(L) + "\n",
                                            encoding="utf-8")
    print(f"  -> {(SEC / 'tab_dispersion.tex').relative_to(J.ROOT)}")

    # --------------------------------------------------- arch table (j28)
    # SUPERSEDED. j28 has one run per cell; j30 has twenty per architecture and
    # its table (tab_dispdist, from j31) is what Section X uses. The j28 result
    # still stands on its own terms and the generator is kept for reference,
    # but the .tex is no longer emitted, because an unused table file in
    # sections/ is a trap for the next person to build the paper.
    p28 = J.RESULTS / "j28_arch_dispersion.json"
    if False and p28.exists():
        j28 = json.loads(p28.read_text())
        A = [
            "% GENERATED by journal/scripts/j29_dispersion_figure.py",
            r"\begin{table}[t]",
            r"\caption{The null change applied to three architectures. All six "
            r"score $F_1 = 1.0000$ on the generated benchmark. The entire "
            r"spread of the experiment lies inside one architecture, so the "
            r"released checkpoints cannot be read as an architecture "
            r"ranking.}",
            r"\label{tab:archdispersion}",
            r"\centering\tabfont",
            r"\begin{tabular}{lrrr}",
            r"\toprule",
            r"Architecture & global first & seed first & Swing \\",
            r"\midrule",
        ]
        for arch, v in j28["summary"].items():
            bold = r"\textbf" if v["swing"] == j28["max_null_swing"] else ""
            A.append(f"{arch.upper()} & {v['global_first']:.3f} & "
                     f"{v['seed_first']:.3f} & "
                     f"{bold}{{{v['swing']:.3f}}} \\\\"
                     if bold else
                     f"{arch.upper()} & {v['global_first']:.3f} & "
                     f"{v['seed_first']:.3f} & {v['swing']:.3f} \\\\")
        A += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
        (SEC / "tab_archdispersion.tex").write_text("\n".join(A) + "\n",
                                                    encoding="utf-8")
        print(f"  -> {(SEC / 'tab_archdispersion.tex').relative_to(J.ROOT)}")

    J.save("j29_dispersion_figure", dict(
        n_configs=len(rows),
        benchmark_range=summ["test_id"]["range"],
        real_range=summ["conf"]["range"],
        benchmark_distinct=summ["test_id"]["n_distinct"],
        real_distinct=summ["conf"]["n_distinct"]))


if __name__ == "__main__":
    main()
